#Integers
num1=27
num2=29

#addition
total=num1+num2
print(total)

#subtraction
total1=num1-num2
print(total1)

#division
div=num2/num1
print(div)

#modulus
mod=num2%num1
print(mod)

#Floor operator
floor=num2//num1
print(floor)


#exponent
exp=num1**2
print(exp)

#floats
num3=27.5
print(num3)

#roundoff
num4=round(num3)
print (num3)
